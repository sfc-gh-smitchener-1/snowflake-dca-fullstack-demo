-- ============================================================================
-- UNITED RENTALS DEMO - Load Data: Stage + COPY INTO
-- ============================================================================
--
-- Loads generated CSV data from internal stage into RAW tables.
-- Uses INFER_SCHEMA for dynamic column detection and MATCH_BY_COLUMN_NAME
-- for resilient loading (same pattern as core DCA 04_load_data.sql).
--
-- Prerequisites: Run 01_ur_setup.sql first, upload CSVs to stage.
-- RUN AS: DATA_ADMIN
-- ============================================================================

USE ROLE DATA_ADMIN;
USE DATABASE RAW_DEV;
USE SCHEMA RAW_DEV.UNITED_RENTALS;
USE WAREHOUSE INGEST_WH;

-- ═══════════════════════════════════════════════════════════════════════════
-- INTERNAL STAGE
-- ═══════════════════════════════════════════════════════════════════════════

CREATE OR REPLACE STAGE RAW_DEV.UNITED_RENTALS.UR_DATA_STAGE
    DIRECTORY = (ENABLE = TRUE)
    COMMENT = 'United Rentals demo data files';

-- Upload CSVs: PUT file:///path/to/demos/united-rentals/data/*.csv @UR_DATA_STAGE;

-- ═══════════════════════════════════════════════════════════════════════════
-- FILE FORMAT
-- ═══════════════════════════════════════════════════════════════════════════

CREATE OR REPLACE FILE FORMAT RAW_DEV.UNITED_RENTALS.UR_CSV_FORMAT
    TYPE = 'CSV'
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    TRIM_SPACE = TRUE
    ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE
    COMMENT = 'CSV format for UR data files';

-- ═══════════════════════════════════════════════════════════════════════════
-- RAW TABLES (explicit DDL for clarity and governance tagging)
-- ═══════════════════════════════════════════════════════════════════════════

