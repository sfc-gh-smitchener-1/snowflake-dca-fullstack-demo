-- ═══════════════════════════════════════════════════════════════════════════
-- COPY INTO (load from stage)
-- ═══════════════════════════════════════════════════════════════════════════

COPY INTO RAW_DEV.UNITED_RENTALS.BRANCHES
    FROM @RAW_DEV.UNITED_RENTALS.UR_DATA_STAGE/branches.csv
    FILE_FORMAT = RAW_DEV.UNITED_RENTALS.UR_CSV_FORMAT
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    ON_ERROR = 'CONTINUE';

COPY INTO RAW_DEV.UNITED_RENTALS.EQUIPMENT
    FROM @RAW_DEV.UNITED_RENTALS.UR_DATA_STAGE/equipment.csv
    FILE_FORMAT = RAW_DEV.UNITED_RENTALS.UR_CSV_FORMAT
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    ON_ERROR = 'CONTINUE';

COPY INTO RAW_DEV.UNITED_RENTALS.CUSTOMERS
    FROM @RAW_DEV.UNITED_RENTALS.UR_DATA_STAGE/customers.csv
    FILE_FORMAT = RAW_DEV.UNITED_RENTALS.UR_CSV_FORMAT
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    ON_ERROR = 'CONTINUE';

COPY INTO RAW_DEV.UNITED_RENTALS.RENTAL_CONTRACTS
    FROM @RAW_DEV.UNITED_RENTALS.UR_DATA_STAGE/rental_contracts.csv
    FILE_FORMAT = RAW_DEV.UNITED_RENTALS.UR_CSV_FORMAT
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    ON_ERROR = 'CONTINUE';

COPY INTO RAW_DEV.UNITED_RENTALS.MAINTENANCE_RECORDS
    FROM @RAW_DEV.UNITED_RENTALS.UR_DATA_STAGE/maintenance_records.csv
    FILE_FORMAT = RAW_DEV.UNITED_RENTALS.UR_CSV_FORMAT
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    ON_ERROR = 'CONTINUE';

COPY INTO RAW_DEV.UNITED_RENTALS.TELEMATICS
    FROM @RAW_DEV.UNITED_RENTALS.UR_DATA_STAGE/telematics.csv
    FILE_FORMAT = RAW_DEV.UNITED_RENTALS.UR_CSV_FORMAT
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    ON_ERROR = 'CONTINUE';

-- ═══════════════════════════════════════════════════════════════════════════
-- VERIFY LOAD
-- ═══════════════════════════════════════════════════════════════════════════

SELECT 'BRANCHES' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM RAW_DEV.UNITED_RENTALS.BRANCHES
UNION ALL SELECT 'EQUIPMENT', COUNT(*) FROM RAW_DEV.UNITED_RENTALS.EQUIPMENT
UNION ALL SELECT 'CUSTOMERS', COUNT(*) FROM RAW_DEV.UNITED_RENTALS.CUSTOMERS
UNION ALL SELECT 'RENTAL_CONTRACTS', COUNT(*) FROM RAW_DEV.UNITED_RENTALS.RENTAL_CONTRACTS
UNION ALL SELECT 'MAINTENANCE_RECORDS', COUNT(*) FROM RAW_DEV.UNITED_RENTALS.MAINTENANCE_RECORDS
UNION ALL SELECT 'TELEMATICS', COUNT(*) FROM RAW_DEV.UNITED_RENTALS.TELEMATICS
ORDER BY TABLE_NAME;
